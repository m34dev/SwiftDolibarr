	/// Returns nil for an empty string, as Dolibarr returns empty strings for unset codes
	private static func nonEmpty(_ value: String?) -> String? {
		guard let value, !value.isEmpty else { return nil }
		return value
	}

	// MARK: - Protocol methods

	override public func hash(into hasher: inout Hasher) {
		hasher.combine(ref)
		hasher.combine(trackId)
		hasher.combine(subject)
		hasher.combine(message)
		hasher.combine(optional: thirdPartyId)
		hasher.combine(optional: projectId)
		hasher.combine(optional: contractId)
		hasher.combine(optional: userCreateId)
		hasher.combine(optional: userAssignId)
		hasher.combine(optional: originEmail)
		hasher.combine(optional: typeCode)
		hasher.combine(optional: typeLabel)
		hasher.combine(optional: categoryCode)
		hasher.combine(optional: categoryLabel)
		hasher.combine(optional: severityCode)
		hasher.combine(optional: severityLabel)
		hasher.combine(optional: progress)
		hasher.combine(optional: dateReadTimestamp)
		hasher.combine(optional: dateLastMessageSentTimestamp)
		hasher.combine(optional: dateClose)
		hasher.combine(optional: lastMainDoc)
		hasher.combine(optional: externalContactIds)
		hasher.combine(optional: internalContactIds)
		hasher.combine(optional: linkedObjectsIds)
		hasher.combine(optional: messages)
		super.hash(into: &hasher)
	}

	override public func isEqual(to other: CommonBusinessObject) -> Bool {
		guard let other = other as? DolibarrTicket else { return false }
		return ref == other.ref
		&& trackId == other.trackId
		&& subject == other.subject
		&& message == other.message
		&& thirdPartyId == other.thirdPartyId
		&& projectId == other.projectId
		&& contractId == other.contractId
		&& userCreateId == other.userCreateId
		&& userAssignId == other.userAssignId
		&& originEmail == other.originEmail
		&& typeCode == other.typeCode
		&& typeLabel == other.typeLabel
		&& categoryCode == other.categoryCode
		&& categoryLabel == other.categoryLabel
		&& severityCode == other.severityCode
		&& severityLabel == other.severityLabel
		&& progress == other.progress
		&& dateReadTimestamp == other.dateReadTimestamp
		&& dateLastMessageSentTimestamp == other.dateLastMessageSentTimestamp
		&& dateClose == other.dateClose
		&& lastMainDoc == other.lastMainDoc
		&& externalContactIds == other.externalContactIds
		&& internalContactIds == other.internalContactIds
		&& linkedObjectsIds == other.linkedObjectsIds
		&& messages == other.messages
		&& super.isEqual(to: other)
	}

	/// Encodes the create and update body
	///
	/// Leaves out the status, the read-only dates, the tracking ID, the labels, the contacts and the messages.
	/// The reference is only sent when set, so Dolibarr numbers a new ticket.
	/// The assigned user is only sent on create, when ``id`` is empty.
	override public func encode(to encoder: any Encoder) throws {
		var container = encoder.container(keyedBy: CodingKeys.self)
		try container.encodeIfNotEmpty(ref, forKey: .ref)
		try container.encode(subject, forKey: .subject)
		try container.encode(message, forKey: .message)
		try container.encode(thirdPartyId ?? "", forKey: .thirdPartyId)
		try container.encode(thirdPartyId ?? "", forKey: .thirdPartyIdLegacy)
		try container.encode(projectId ?? "", forKey: .projectId)
		try container.encodeIfPresent(contractId, forKey: .contractId)
		if id.isEmpty {
			try container.encodeIfPresent(userAssignId, forKey: .userAssignId)
		}
		try container.encodeIfPresent(originEmail, forKey: .originEmail)
		try container.encode(typeCode ?? "", forKey: .typeCode)
		try container.encode(categoryCode ?? "", forKey: .categoryCode)
		try container.encode(severityCode ?? "", forKey: .severityCode)
		try container.encodeIfPresent(progress.map { min(max($0, 0), 100) }, forKey: .progress)
		try super.encode(to: encoder)
	}

}
