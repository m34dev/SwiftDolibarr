/// A Dolibarr ticket (helpdesk) object.
///
/// Maps to the Dolibarr `/tickets` REST API endpoint. A ticket has a ``subject``,
/// an initial ``message``, a public ``trackId``, and can be linked to a third party,
/// a project and a contract, and assigned to a user.
///
/// ## Overview
///
/// Each ticket has a ``status`` (``DolibarrObjectStatus/tickets``), type, category and severity codes
/// from the ticket dictionaries, a progress percentage, and, when fetched by ID, reference
/// or tracking ID, its ``messages``.
///
/// Dolibarr never returns the public and private notes of a ticket.
/// `date_validation` is the date the ticket was read, also available as ``dateRead``.
///
/// ## Encoding
///
/// The create (`POST /tickets`) and update (`PUT /tickets/{id}`) body never includes the status:
/// use `POST /tickets/{id}/close` (Dolibarr v25+) to close or cancel a ticket.
/// The third party is sent as both `socid` and `fk_soc`, since Dolibarr up to v24 reads one on create
/// and saves the other. The assigned user is only sent on create, as Dolibarr v25 rejects a changed
/// assigned user on update: use `POST /tickets/{id}/assign` instead.
///
/// - Note: Requires the **Ticket** module to be activated in Dolibarr.
/// - SeeAlso: ``DolibarrTicketMessage``
/// - SeeAlso: ``DolibarrTicketType``, ``DolibarrTicketCategory``, ``DolibarrTicketSeverity``
#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
@Observable
#endif
public final class DolibarrTicket: CommonBusinessObject {

	// MARK: - Properties

	// Required

	/// Ticket reference
	public var ref: String

	/// Public tracking ID, generated by Dolibarr on create when empty
	///
	/// - Mapped Dolibarr property: **track_id**
	public var trackId: String

	/// Ticket subject
	public var subject: String

	/// Initial message (HTML)
	public var message: String

	// Optional

	/// Associated third party ID
	///
	/// - Mapped Dolibarr property: **fk_soc** (or **socid**)
	public var thirdPartyId: String?

	/// Associated project ID
	///
	/// - Mapped Dolibarr property: **fk_project**
	public var projectId: String?

	/// Associated contract ID
	///
	/// - Mapped Dolibarr property: **fk_contract**
	public var contractId: String?

	/// Creator user ID
	///
	/// - Mapped Dolibarr property: **fk_user_create**
	public var userCreateId: String?

	/// Assigned user ID
	///
	/// - Mapped Dolibarr property: **fk_user_assign**
	public var userAssignId: String?

	/// Email of the creator, when the ticket was created from an email or the public interface
	///
	/// - Mapped Dolibarr property: **origin_email**
	public var originEmail: String?

	/// Ticket type code, from the `c_ticket_type` dictionary
	///
	/// - Mapped Dolibarr property: **type_code**
	public var typeCode: String?

	/// Ticket type label, translated by Dolibarr
	///
	/// - Mapped Dolibarr property: **type_label**
	public var typeLabel: String?

	/// Ticket category code, from the `c_ticket_category` dictionary
	///
	/// - Mapped Dolibarr property: **category_code**
	public var categoryCode: String?

	/// Ticket category label, translated by Dolibarr
	///
	/// - Mapped Dolibarr property: **category_label**
	public var categoryLabel: String?

	/// Ticket severity code, from the `c_ticket_severity` dictionary
	///
	/// - Mapped Dolibarr property: **severity_code**
	public var severityCode: String?

	/// Ticket severity label, translated by Dolibarr
	///
	/// - Mapped Dolibarr property: **severity_label**
	public var severityLabel: String?

	/// Progress in percent (0-100)
	public var progress: Int?

	/// Read date (Unix timestamp)
	///
	/// - Mapped Dolibarr property: **date_read**
	public var dateReadTimestamp: Int?

	/// Date of the last message sent (Unix timestamp)
	///
	/// - Mapped Dolibarr property: **date_last_msg_sent**
	public var dateLastMessageSentTimestamp: Int?

	/// Closing date (Unix timestamp)
	///
	/// - Mapped Dolibarr property: **date_close**
	public var dateClose: Int?

	/// Last generated main document path
	///
	/// - Mapped Dolibarr property: **last_main_doc**
	public var lastMainDoc: String?

	/// External contact IDs
	///
	/// - Mapped Dolibarr property: **contacts_ids**
	public var externalContactIds: [String]?

	/// Internal contact (user) IDs
	///
	/// - Mapped Dolibarr property: **contacts_ids_internal**
	public var internalContactIds: [String]?

	/// IDs of linked objects, keyed by element type
	///
	/// - Mapped Dolibarr property: **linkedObjectsIds**
	public var linkedObjectsIds: [String: [String: String]]?

	/// Ticket messages, newest first, only returned when fetching a single ticket
	///
	/// Read only: never encoded. Add a message with ``DolibarrTicketMessage`` instead.
	public var messages: [DolibarrTicketMessage]?

	// Computed

	/// ID of the user who created the ticket
	override public var createdByUserId: String? {
		super.createdByUserId ?? Self.userId(userCreateId)
	}

	/// Associated ticket status type
	override public var status: DolibarrObjectStatus {
		guard let status = DolibarrObjectStatus.tickets.first(where: { $0.code == statusCode }) else { return .unknown }
		return status
	}

	/// Whether the ticket is closed or canceled
	public var isClosed: Bool {
		status == .ticketClosed || status == .ticketCanceled
	}

	/// Read date
	public var dateRead: Date? {
		Self.date(from: dateReadTimestamp) ?? dateValidated
	}

	/// Date of the last message sent
	public var dateLastMessageSent: Date? {
		Self.date(from: dateLastMessageSentTimestamp)
	}

	/// Closing date
	public var dateClosed: Date? {
		Self.date(from: dateClose)
	}

	// MARK: - Enums

	enum CodingKeys: String, CodingKey {
		case ref
		case trackId = "track_id"
		case subject
		case message
		case thirdPartyId = "fk_soc"
		case thirdPartyIdLegacy = "socid"
		case projectId = "fk_project"
		case contractId = "fk_contract"
		case userCreateId = "fk_user_create"
		case userAssignId = "fk_user_assign"
		case originEmail = "origin_email"
		case typeCode = "type_code"
		case typeLabel = "type_label"
		case categoryCode = "category_code"
		case categoryLabel = "category_label"
		case severityCode = "severity_code"
		case severityLabel = "severity_label"
		case progress
		case dateReadTimestamp = "date_read"
		case dateLastMessageSentTimestamp = "date_last_msg_sent"
		case dateClose = "date_close"
		case lastMainDoc = "last_main_doc"
		case externalContactIds = "contacts_ids"
		case internalContactIds = "contacts_ids_internal"
		case linkedObjectsIds
		case messages
	}

	// MARK: - Inits

	public init(
		ref: String = "",
		trackId: String = "",
		subject: String = "",
		message: String = "",
		thirdPartyId: String? = nil,
		projectId: String? = nil,
		contractId: String? = nil,
		userCreateId: String? = nil,
		userAssignId: String? = nil,
		originEmail: String? = nil,
		typeCode: String? = nil,
		typeLabel: String? = nil,
		categoryCode: String? = nil,
		categoryLabel: String? = nil,
		severityCode: String? = nil,
		severityLabel: String? = nil,
		progress: Int? = nil,
		dateReadTimestamp: Int? = nil,
		dateLastMessageSentTimestamp: Int? = nil,
		dateClose: Int? = nil,
		lastMainDoc: String? = nil,
		externalContactIds: [String]? = nil,
		internalContactIds: [String]? = nil,
		linkedObjectsIds: [String: [String: String]]? = nil,
		messages: [DolibarrTicketMessage]? = nil,
		id: String = "",
		statusCode: String = "",
		arrayOptions: [String: MultiType]? = nil
	) {
		self.ref = ref
		self.trackId = trackId
		self.subject = subject
		self.message = message
		self.thirdPartyId = thirdPartyId
		self.projectId = projectId
		self.contractId = contractId
		self.userCreateId = userCreateId
		self.userAssignId = userAssignId
		self.originEmail = originEmail
		self.typeCode = typeCode
		self.typeLabel = typeLabel
		self.categoryCode = categoryCode
		self.categoryLabel = categoryLabel
		self.severityCode = severityCode
		self.severityLabel = severityLabel
		self.progress = progress
		self.dateReadTimestamp = dateReadTimestamp
		self.dateLastMessageSentTimestamp = dateLastMessageSentTimestamp
		self.dateClose = dateClose
		self.lastMainDoc = lastMainDoc
		self.externalContactIds = externalContactIds
		self.internalContactIds = internalContactIds
		self.linkedObjectsIds = linkedObjectsIds
		self.messages = messages
		super.init(
			id: id,
			statusCode: statusCode,
			arrayOptions: arrayOptions
		)
	}

	public required init(from decoder: any Decoder) throws {
		do {
			#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
			Logger.logWithoutSignal("\(Self.self).init.decode", category: .api)
			#endif
			let container = try decoder.container(keyedBy: CodingKeys.self)
			self.ref = try container.decodeIfPresent(MultiType.self, forKey: .ref)?.stringValue ?? ""
			self.trackId = try container.decodeIfPresent(String.self, forKey: .trackId) ?? ""
			self.subject = try container.decodeIfPresent(String.self, forKey: .subject) ?? ""
			self.message = try container.decodeIfPresent(String.self, forKey: .message) ?? ""
			self.thirdPartyId = try container.decodeIdIfPresent(forKey: .thirdPartyId) ?? container.decodeIdIfPresent(forKey: .thirdPartyIdLegacy)
			self.projectId = try container.decodeIdIfPresent(forKey: .projectId)
			self.contractId = try container.decodeIdIfPresent(forKey: .contractId)
			self.userCreateId = try container.decodeIdIfPresent(forKey: .userCreateId)
			self.userAssignId = try container.decodeIdIfPresent(forKey: .userAssignId)
			self.originEmail = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .originEmail))
			self.typeCode = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .typeCode))
			self.typeLabel = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .typeLabel))
			self.categoryCode = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .categoryCode))
			self.categoryLabel = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .categoryLabel))
			self.severityCode = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .severityCode))
			self.severityLabel = Self.nonEmpty(try container.decodeIfPresent(String.self, forKey: .severityLabel))
			self.progress = try container.decodeIfPresent(MultiType.self, forKey: .progress)?.intValue
			self.dateReadTimestamp = try container.decodeIfPresent(MultiType.self, forKey: .dateReadTimestamp)?.intValue
			self.dateLastMessageSentTimestamp = try container.decodeIfPresent(MultiType.self, forKey: .dateLastMessageSentTimestamp)?.intValue
			self.dateClose = try container.decodeIfPresent(MultiType.self, forKey: .dateClose)?.intValue
			self.lastMainDoc = try container.decodeIfPresent(String.self, forKey: .lastMainDoc)
			self.externalContactIds = (try? container.decodeIfPresent([MultiType].self, forKey: .externalContactIds))?.map(\.stringValue)
			self.internalContactIds = (try? container.decodeIfPresent([MultiType].self, forKey: .internalContactIds))?.map(\.stringValue)
			self.linkedObjectsIds = try? container.decodeIfPresent([String: [String: String]].self, forKey: .linkedObjectsIds)
			self.messages = try container.decodeIfPresent([DolibarrTicketMessage].self, forKey: .messages)
			try super.init(from: decoder)
			#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
			Logger.logWithoutSignal("\(Self.self).init.decoded", category: .api)
			#endif
		} catch let error as DecodingError {
			#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
			Logger.logDecodingError(error, decodeContext: "\(Self.self).init")
			#endif
			throw error
		} catch {
			#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
			Logger.logErrorWithSignal(error, context: "\(Self.self).init", category: .api)
			#endif
			throw error
		}
	}

