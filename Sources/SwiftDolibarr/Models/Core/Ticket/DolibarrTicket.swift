		self.projectId = source.projectId
		self.contractId = source.contractId
		self.userCreateId = source.userCreateId
		self.userAssignId = source.userAssignId
		self.originEmail = source.originEmail
		self.typeCode = source.typeCode
		self.typeLabel = source.typeLabel
		self.categoryCode = source.categoryCode
		self.categoryLabel = source.categoryLabel
