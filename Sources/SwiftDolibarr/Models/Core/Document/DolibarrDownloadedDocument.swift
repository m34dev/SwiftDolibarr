import Foundation
#if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
import OSLog
#endif

/// A document file downloaded or generated by Dolibarr.
///
/// Returned by the Dolibarr `GET /documents/download` and
/// `PUT /documents/builddoc` REST API endpoints. The file ``content``
/// is encoded as described by ``encoding`` (usually `base64`).
///
/// - SeeAlso: ``DolibarrDocument``
public struct DolibarrDownloadedDocument: Decodable, Sendable {

    // MARK: - Properties

    /// File name.
    public var filename: String

    /// File MIME type (e.g. `application/pdf`).
    ///
    /// - Mapped Dolibarr property: **content-type**
    public var contentType: String

    /// File size in bytes.
    public var filesize: Int

    /// Encoded file content.
    public var content: String

    /// Content encoding (e.g. `base64`).
    public var encoding: String

    // MARK: - Computed properties

    /// Decoded file data (base64 content is decoded, other content is returned as UTF-8), or `nil` if base64 content is invalid.
    public var data: Data? {
        encoding == "base64" ? Data(base64Encoded: content) : Data(content.utf8)
    }

    // MARK: - Enums

    enum CodingKeys: String, CodingKey {
        case filename
        case contentType = "content-type"
        case filesize
        case content
        case encoding
    }

    // MARK: - Inits

    public init(
        filename: String = "",
        contentType: String = "",
        filesize: Int = 0,
        content: String = "",
        encoding: String = "",
    ) {
        self.filename = filename
        self.contentType = contentType
        self.filesize = filesize
        self.content = content
        self.encoding = encoding
    }

    public init(from decoder: any Decoder) throws {
        do {
            #if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
            Logger.logWithoutSignal("\(Self.self).init.decode", category: .api)
            #endif
            let container = try decoder.container(keyedBy: CodingKeys.self)
            self.filename = try container.decode(String.self, forKey: .filename)
            self.contentType = try container.decode(String.self, forKey: .contentType)
            self.filesize = try container.decode(Int.self, forKey: .filesize)
            self.content = try container.decode(String.self, forKey: .content)
            self.encoding = try container.decode(String.self, forKey: .encoding)
            #if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
            Logger.logWithoutSignal("\(Self.self).init.decoded", category: .api)
            #endif
        } catch let error as DecodingError {
            #if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
            Logger.logDecodingError(error, decodeContext: "\(Self.self).init")
            #endif
            throw error
        } catch {
            #if os(iOS) || os(macOS) || os(watchOS) || os(tvOS) || os(visionOS)
            Logger.logErrorWithSignal(error, context: "\(Self.self).init", category: .api)
            #endif
            throw error
        }
    }
}
